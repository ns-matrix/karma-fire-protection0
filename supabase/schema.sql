-- Karma Fire Protection: GitHub Pages + Supabase CRM
-- Run once in Supabase SQL Editor. Then add admin user UUIDs to public.admin_users.
create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.leads (
  id uuid primary key default gen_random_uuid(),
  lead_number bigint generated by default as identity unique,
  name text not null check (char_length(name) between 2 and 100),
  phone text not null check (char_length(phone) between 7 and 25),
  email text not null check (char_length(email) <= 160),
  company text,
  building_type text not null,
  service text not null,
  location text not null,
  message text,
  contact_method text default 'Phone Call',
  consent boolean not null default false check (consent = true),
  source text default 'Website',
  medium text,
  campaign text,
  landing_page text,
  visitor_uuid text,
  session_uuid text,
  status text not null default 'New' check (status in ('New','Contacted','Qualified','Proposal Sent','Converted','Lost')),
  assigned_to text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.visitor_events (
  id uuid primary key default gen_random_uuid(),
  visitor_uuid text,
  session_uuid text,
  page_path text not null,
  page_title text,
  referrer text,
  source text default 'Direct',
  medium text,
  campaign text,
  device_category text,
  consent_state text default 'undecided',
  created_at timestamptz not null default now()
);

create index if not exists leads_created_at_idx on public.leads(created_at desc);
create index if not exists leads_status_idx on public.leads(status);
create index if not exists leads_service_idx on public.leads(service);
create index if not exists visitor_events_created_at_idx on public.visitor_events(created_at desc);
create index if not exists visitor_events_page_path_idx on public.visitor_events(page_path);

create or replace function public.is_karma_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (select 1 from public.admin_users where user_id = auth.uid());
$$;

alter table public.admin_users enable row level security;
alter table public.leads enable row level security;
alter table public.visitor_events enable row level security;

drop policy if exists "Admins can read admin list" on public.admin_users;
create policy "Admins can read admin list" on public.admin_users
for select to authenticated using (public.is_karma_admin());

drop policy if exists "Public can submit enquiries" on public.leads;
create policy "Public can submit enquiries" on public.leads
for insert to anon, authenticated
with check (
  consent = true
  and char_length(trim(name)) between 2 and 100
  and char_length(trim(phone)) between 7 and 25
  and char_length(trim(email)) <= 160
);

drop policy if exists "Admins can read leads" on public.leads;
create policy "Admins can read leads" on public.leads
for select to authenticated using (public.is_karma_admin());

drop policy if exists "Admins can update leads" on public.leads;
create policy "Admins can update leads" on public.leads
for update to authenticated using (public.is_karma_admin()) with check (public.is_karma_admin());

drop policy if exists "Admins can delete leads" on public.leads;
create policy "Admins can delete leads" on public.leads
for delete to authenticated using (public.is_karma_admin());

drop policy if exists "Public can record page views" on public.visitor_events;
create policy "Public can record page views" on public.visitor_events
for insert to anon, authenticated
with check (char_length(page_path) <= 500);

drop policy if exists "Admins can read visitor events" on public.visitor_events;
create policy "Admins can read visitor events" on public.visitor_events
for select to authenticated using (public.is_karma_admin());

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;

drop trigger if exists leads_updated_at on public.leads;
create trigger leads_updated_at before update on public.leads
for each row execute function public.set_updated_at();

